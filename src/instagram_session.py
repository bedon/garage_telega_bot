"""Read/write the Instagram session shared by yt-dlp and instaloader.

The session lives in two files under config.INSTAGRAM_DATA_DIR:
- cookies.txt     Netscape cookie file (yt-dlp format), written by `make ig-login`
                  or exported from a browser.
- user_agent.txt  The User-Agent the session was created with. Every request
                  must reuse it, otherwise Instagram invalidates the session.
"""

import os
import time
from pathlib import Path

import config

INSTAGRAM_DOMAIN = ".instagram.com"
NETSCAPE_HEADER = "# Netscape HTTP Cookie File\n# Generated by garage_telega_bot ig_login\n\n"


def user_agent() -> str:
    try:
        ua = config.INSTAGRAM_USER_AGENT_FILE.read_text().strip()
    except OSError:
        ua = ""
    return ua or config.DEFAULT_USER_AGENT


def cookies_file() -> Path | None:
    path = config.INSTAGRAM_COOKIES_FILE
    return path if path.is_file() else None


def read_cookies(path: Path) -> dict[str, str]:
    """Parse a Netscape cookie file and return Instagram cookies as name -> value."""
    cookies = {}
    for line in path.read_text().splitlines():
        if line.startswith("#HttpOnly_"):
            line = line[len("#HttpOnly_"):]
        elif not line.strip() or line.startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) == 7 and "instagram.com" in fields[0]:
            cookies[fields[5]] = fields[6]
    return cookies


def write_cookies(cookies: dict[str, str], path: Path) -> None:
    """Write cookies as a Netscape cookie file readable by yt-dlp."""
    expires = int(time.time()) + 365 * 24 * 3600
    lines = [
        f"{INSTAGRAM_DOMAIN}\tTRUE\t/\tTRUE\t{expires}\t{name}\t{value}\n"
        for name, value in cookies.items()
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(NETSCAPE_HEADER + "".join(lines))
    os.chmod(path, 0o600)


def save_session(cookies: dict[str, str], ua: str) -> None:
    write_cookies(cookies, config.INSTAGRAM_COOKIES_FILE)
    config.INSTAGRAM_USER_AGENT_FILE.write_text(ua + "\n")
